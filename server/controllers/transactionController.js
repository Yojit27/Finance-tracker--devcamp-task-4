import mongoose from 'mongoose';
import Transaction, { FREQUENCIES } from '../models/Transaction.js';
import Category from '../models/Category.js';
import ApiError from '../utils/ApiError.js';
import asyncHandler from '../utils/asyncHandler.js';
import { throwIfErrors, round2 } from '../utils/validate.js';
import { parseDateOnly, addInterval } from '../utils/dates.js';
import { sendCsv } from '../utils/csv.js';

const escapeRegex = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// Builds the Mongo filter from query params. Always scoped to the logged-in user.
const buildFilter = (query, userId) => {
  const filter = { user: userId };
  const errors = {};

  if (query.type) {
    if (!['income', 'expense'].includes(query.type)) errors.type = 'Type must be income or expense';
    else filter.type = query.type;
  }
  if (query.category) {
    if (!mongoose.isValidObjectId(String(query.category))) errors.category = 'Invalid category';
    else filter.category = String(query.category);
  }
  if (query.startDate || query.endDate) {
    filter.date = {};
    if (query.startDate) {
      const d = parseDateOnly(String(query.startDate));
      if (!d) errors.startDate = 'Invalid start date';
      else filter.date.$gte = d;
    }
    if (query.endDate) {
      const d = parseDateOnly(String(query.endDate));
      if (!d) errors.endDate = 'Invalid end date';
      else filter.date.$lte = d;
    }
  }
  if (query.search) filter.title = { $regex: escapeRegex(String(query.search).trim()), $options: 'i' };

  throwIfErrors(errors);
  return filter;
};

// Validates and cleans a transaction body (used by create and update).
async function parsePayload(body, userId) {
  const errors = {};
  const data = {};

  const title = String(body.title ?? '').trim();
  if (!title) errors.title = 'Title is required';
  else if (title.length > 100) errors.title = 'Title must be 100 characters or fewer';
  data.title = title;

  const amount = Number(body.amount);
  if (body.amount === '' || body.amount === null || body.amount === undefined || !Number.isFinite(amount) || amount <= 0) {
    errors.amount = 'Amount must be a number greater than 0';
  } else if (amount > 1e12) {
    errors.amount = 'Amount is too large';
  } else {
    data.amount = round2(amount);
  }

  if (!['income', 'expense'].includes(body.type)) errors.type = 'Type must be income or expense';
  data.type = body.type;

  const date = parseDateOnly(body.date);
  if (!date) errors.date = 'A valid date is required';
  data.date = date;

  const categoryId = String(body.category ?? '');
  if (!mongoose.isValidObjectId(categoryId)) {
    errors.category = 'Category is required';
  } else if (!errors.type) {
    const cat = await Category.findOne({ _id: categoryId, user: userId });
    if (!cat) errors.category = 'Category not found';
    else if (cat.type !== body.type) errors.category = `Pick an ${body.type} category`;
  }
  data.category = categoryId;

  data.isRecurring = body.isRecurring === true || body.isRecurring === 'true';
  if (data.isRecurring) {
    if (!FREQUENCIES.includes(body.frequency)) errors.frequency = 'Choose how often this repeats';
    else data.frequency = body.frequency;
  } else {
    data.frequency = null;
  }

  throwIfErrors(errors);
  return data;
}

const populateCategory = (q) => q.populate('category', 'name type');

export const listTransactions = asyncHandler(async (req, res) => {
  const filter = buildFilter(req.query, req.user._id);
  const data = await populateCategory(Transaction.find(filter).sort({ date: -1, createdAt: -1 }));
  const summary = data.reduce(
    (acc, t) => {
      acc[t.type] = round2(acc[t.type] + t.amount);
      return acc;
    },
    { income: 0, expense: 0 }
  );
  res.json({ success: true, count: data.length, summary, data });
});

export const createTransaction = asyncHandler(async (req, res) => {
  const data = await parsePayload(req.body, req.user._id);
  data.nextRunDate = data.isRecurring ? addInterval(data.date, data.frequency) : null;
  const created = await Transaction.create({ ...data, user: req.user._id });
  const populated = await populateCategory(Transaction.findById(created._id));
  res.status(201).json({ success: true, message: 'Transaction added', data: populated });
});

export const updateTransaction = asyncHandler(async (req, res) => {
  const doc = req.resource;
  const data = await parsePayload(req.body, req.user._id);

  if (doc.recurringSource && data.isRecurring) {
    throw new ApiError(400, 'A transaction generated by a recurring rule cannot itself be made recurring', {
      isRecurring: 'Edit the original recurring transaction instead',
    });
  }

  // Keep the existing schedule position when only other fields changed, so nothing is generated twice.
  const sameSchedule =
    doc.isRecurring && data.isRecurring && doc.frequency === data.frequency && doc.date.getTime() === data.date.getTime();
  data.nextRunDate = data.isRecurring ? (sameSchedule ? doc.nextRunDate : addInterval(data.date, data.frequency)) : null;

  doc.set(data);
  await doc.save();
  const populated = await populateCategory(Transaction.findById(doc._id));
  res.json({ success: true, message: 'Transaction updated', data: populated });
});

export const deleteTransaction = asyncHandler(async (req, res) => {
  await req.resource.deleteOne();
  res.json({ success: true, message: 'Transaction deleted' });
});

export const exportTransactions = asyncHandler(async (req, res) => {
  const filter = buildFilter(req.query, req.user._id);
  const rows = await populateCategory(Transaction.find(filter).sort({ date: -1, createdAt: -1 }));
  const csv = [
    ['Date', 'Title', 'Type', 'Category', 'Amount', 'Recurring'],
    ...rows.map((t) => [
      t.date.toISOString().slice(0, 10),
      t.title,
      t.type,
      t.category?.name ?? '',
      t.amount,
      t.isRecurring ? t.frequency : t.recurringSource ? 'auto-generated' : '',
    ]),
  ];
  sendCsv(res, `transactions-${new Date().toISOString().slice(0, 10)}.csv`, csv);
});
